#!/usr/bin/env python3
"""Writes src/runner/gpu-names.ts from a pci.ids (default /usr/share/misc/pci.ids): the Intel and AMD GPUs only."""
import json
import re
import sys
from pathlib import Path

WANTED = {
    "8086": re.compile(r"Graphics|\bArc\b|Iris|Battlemage|Alchemist|\bDG[12]\b|Flex|Data Center GPU|\bXe\b"),
    "1002": re.compile(
        r"Radeon|Navi|Vega|Polaris|Ellesmere|Baffin|Raphael|Rembrandt|Phoenix|Cezanne|Renoir|FirePro|Instinct"
        r"|Vangogh|Barcelo|Lucienne|Hawk Point|Strix"
    ),
}
NOT_GPU = re.compile(r"Audio|HDMI")

source = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/misc/pci.ids")
text = source.read_text(encoding="utf8", errors="replace")
version = re.search(r"^#\s*Version:\s*(\S+)", text, re.M)
names = {vendor: {} for vendor in WANTED}
vendor = None
for line in text.splitlines():
    found = re.match(r"^([0-9a-f]{4})  ", line)
    if found:
        vendor = found.group(1)
        continue
    device = re.match(r"^\t([0-9a-f]{4})  (.+)$", line)
    if device and vendor in WANTED and WANTED[vendor].search(line) and not NOT_GPU.search(line):
        names[vendor][device.group(1)] = device.group(2)

output = Path(__file__).parent.parent / "src/runner/gpu-names.ts"
output.write_text(
    f"// Generated by scripts/gpu-names.py from pci.ids {version.group(1) if version else ''} (https://pci-ids.ucw.cz, "
    "BSD-3-Clause or GPL-2.0-or-later).\n"
    "// A host's own list is often too old to know a new card: run the script again to take in newer ones.\n"
    f"export const GPU_NAMES: Record<string, Record<string, string>> = {json.dumps(names, indent=2)};\n"
)
